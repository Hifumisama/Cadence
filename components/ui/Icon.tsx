/** The app's icons, named by what they MEAN (not by their drawing): changing the icon set
 * only requires touching this file. Replaces the Unicode characters (✎ ✕ ✦ ⋯ ⠿ ▸ ▾ ♪…), whose rendering
 * varies from one font and system to another. A button that has only an icon keeps its `aria-label`. */
const ICONES = {
  agent: Sparkles,
  modifier: Pencil,
  fermer: X,
  ajouter: Plus,
  supprimer: Trash2,
  plus: Ellipsis,
  poignee: GripVertical,
  bas: ChevronDown,
  droite: ChevronRight,
  replierTout: ChevronsDownUp,
  deplierTout: ChevronsUpDown,
  valide: Check,
  alerte: TriangleAlert,
  lecture: Play,
  image: ImageIcone,
  arret: Square,
  musique: Music,
  vide: Circle,
  encours: LoaderCircle,
  fait: CircleCheck,
  echec: CircleX,
  neutre: Minus,
  recherche: Search,
  copier: Copy,
  grille: LayoutGrid,
  liste: List,
  gauche: ChevronLeft,
  agrandir: Maximize2,
  effacer: Eraser,
  importer: Upload,
  personnage: User,
  decor: MapPin,
  prop: Box,
  effet: Flame,
  son: AudioWaveform,
  keyframe: Clapperboard,
  autre: Shapes,
} as const;

export type NomIcone = keyof typeof ICONES;

/** The icon of each asset type (the type states its nature: a face, a place, an object, an effect, a sound…). */
export const ICONE_TYPE_ASSET: Record<string, NomIcone> = {
  personnage: "personnage",
  decor: "decor",
  prop: "prop",
  vfx: "effet",
  keyframe: "keyframe",
  oth: "autre",
};

export function Icone({ nom, taille = 16, className, ...reste }: { nom: NomIcone; taille?: number } & Omit<LucideProps, "size">) {
  const Composant = ICONES[nom];
  return <Composant size={taille} strokeWidth={1.75} aria-hidden="true" focusable="false" className={className ? `icone ${className}` : "icone"} {...reste} />;
}
